export type Language = "zh" | "en";
export type Translate = (key: string, values?: Record<string, string | number>) => string;

export function resolveLanguage(
  setting: string | null | undefined,
  browserLanguage: string,
): Language {
  if (setting === "zh" || setting === "en") return setting;
  return browserLanguage.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function translate(
  language: Language,
  key: string,
  values: Record<string, string | number> = {},
): string {
  const template = language === "en" ? (english[key] ?? key) : key;
  return template.replace(/\{([\w]+)\}/g, (original, name: string) =>
    name in values ? String(values[name]) : original,
  );
}

const Context = createContext<{ language: Language; t: Translate }>({
  language: "zh",
  t: (key, values) => translate("zh", key, values),
});

export function I18nProvider({
  setting,
  children,
}: {
  setting?: string | null;
  children: ReactNode;
}) {
  const language = resolveLanguage(setting, navigator.language);
  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  }, [language]);
  const value = useMemo(
    () => ({
      language,
      t: (key: string, values?: Record<string, string | number>) =>
        translate(language, key, values),
    }),
    [language],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function useI18n() {
  return useContext(Context);
}

export function hasEnglish(key: string) {
  return Object.hasOwn(english, key);
}
