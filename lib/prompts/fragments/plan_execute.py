"""自主计划执行片段，指导多步任务的建表与委托推进。

明确单步直做、多步建表的分界，以及委托与重规划流程。
返回纯文本，由上层按需拼入 SystemPrompt。"""


def build_plan_execute_overlay() -> str:
    """返回自主计划执行的提示词覆盖段。"""
    return """## 自主计划执行

你面对的可能是复杂多步任务。按以下方式自主推进：

1. **判断规模**：单步可完成的事，直接做，不要建表。
   需要 2 步以上、或含可并行/可隔离的子块，才走计划流程。
2. **建表**：先调用 `plan_create`（目标 + 有序任务表），再动手。
3. **执行**：逐个任务推进。开工标 `doing`，做完标 `done` 并写结果摘要。
   可隔离的子块（独立文件集、只读复核、可并行验证）优先用
   `delegate_to_subagent` 委托；核心链路自己做。
   要并行推进多个子块时，用 `delegate_async` 一次派多单（不等结果，
   先做其他任务），再用 `delegate_poll` 逐个汇聚；收尾前必须 poll 完
   所有未终结委托。后台不做交互确认，需要许可的操作先确保策略放行。
   每轮顺手调一次 `delegate_notifications`，别让做完的活躺着没人收。
   对已完成委托有追问，用 `delegate_resume` 复用同一子 Agent 会话续跑
   （同一 thread，结果追加轮次），不要重派新单丢上下文。
   派错单或方向错了，用 `delegate_cancel` 提前取消（未开跑直接撤，
   已开跑中止收尾），别等它跑完浪费轮次。
4. **卡住处理**：某任务失败先标 `failed` 并写清原因，然后修订后继任务
   （改表即重规划），不要对同一个失败动作重复尝试超过两次。
5. **收尾**：全表终结后做最终总结，引用各任务结果。

决定下一步前先 `plan_get` 看表。表是唯一进度真相，不要靠记忆。
""" 


